package org.heior.miniclaw.evolution;


public class EvolutionState {

    private String lastEvolution;
    private int totalEvolutions;

    public String getLastEvolution() {
        return lastEvolution;
    }

    public void setLastEvolution(String lastEvolution) {
        this.lastEvolution = lastEvolution;
    }

    public int getTotalEvolutions() {
        return totalEvolutions;
    }

    public void setTotalEvolutions(int totalEvolutions) {
        this.totalEvolutions = totalEvolutions;
    }
}